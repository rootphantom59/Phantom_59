#!/bin/bash
# ==============================================================
# PHANTOM - ASCII Art Text Generator
# Block Font Generator
# ==============================================================

WIDTH=""
TEXT=""

# --------------------------------------------------------------
# Arguments
# --------------------------------------------------------------
while [[ "$#" -gt 0 ]]; do
    case "$1" in
        -w|--width)
            if [[ -n "$2" && "$2" =~ ^[0-9]+$ ]]; then
                WIDTH="$2"
                shift 2
            else
                echo "Usage: $0 [-w width] [text]"
                exit 1
            fi
            ;;
        *)
            if [ -z "$TEXT" ]; then
                TEXT="$1"
            else
                TEXT="$TEXT $1"
            fi
            shift
            ;;
    esac
done

# --------------------------------------------------------------
# Read text from stdin if no argument was supplied
# --------------------------------------------------------------
if [ -z "$TEXT" ]; then
    read -r TEXT
fi

# --------------------------------------------------------------
# Convert lowercase to uppercase
# --------------------------------------------------------------
TEXT=$(printf '%s' "$TEXT" | tr '[:lower:]' '[:upper:]')

# --------------------------------------------------------------
# PHANTOM ASCII ART ENGINE
# --------------------------------------------------------------
awk -v text="$TEXT" -v width="$WIDTH" '
BEGIN {

    alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZ1234567890?,;:-$=+%#?)(/"

    split(alphabet, chars, "")

    char_idx = 1
    line_idx = 1

    # Space character
    for (i = 1; i <= 6; i++) {
        map[" ", i] = "      "
    }
}

{
    gsub(/\r/, "", $0)

    if ($0 == "") {

        if (line_idx > 1) {
            char_idx++
            line_idx = 1
        }

    } else {

        if (char_idx <= length(chars)) {
            char = chars[char_idx]
            map[char, line_idx] = $0
            line_idx++
        }
    }
}

END {

    split(text, tchars, "")

    for (line = 1; line <= 6; line++) {

        out = ""

        for (i = 1; i <= length(tchars); i++) {

            c = tchars[i]

            if ((c SUBSEP line) in map) {
                out = out map[c, line]
            } else {
                out = out map[" ", line]
            }
        }

        # ------------------------------------------------------
        # Center according to requested width
        # ------------------------------------------------------
        if (width != "" && width > length(out)) {

            pad = int((width - length(out)) / 2)

            padding = ""

            for (p = 1; p <= pad; p++) {
                padding = padding " "
            }

            print padding out

        } else {
            print out
        }
    }
}

